WITH ProductRank AS
(
SELECT*,
DENSE_RANK()
OVER(PARTITION BY CATEGORY ORDER BY PRICE DESC)AS RankNo
FROM PRODUCT3
)

SELECT *
FROM ProductRank
WHERE RankNo=2;