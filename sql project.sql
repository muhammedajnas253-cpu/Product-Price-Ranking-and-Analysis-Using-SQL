CREATE DATABASE PP8;
USE PP8;

CREATE TABLE PRODUCT3
(
P_ID INT PRIMARY KEY AUTO_INCREMENT,
P_NAME VARCHAR(100),
CATEGORY VARCHAR(100),
PRICE DECIMAL(10,2)
);

